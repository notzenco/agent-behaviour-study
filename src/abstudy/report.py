"""Figures, tables and the generated report.

Everything here is produced from the result file, so the numbers in the
report and the numbers in the data cannot drift apart.

Every figure and every table carries a banner when the dataset is synthetic.
A synthetic run must never be mistaken for a finding about real agents.
"""

from __future__ import annotations

import json
import os
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402 - the backend has to be set first
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from abstudy.analysis import (  # noqa: E402
    LogitFit,
    conditional_exposure,
    detector_agreement,
    fisher_comparison,
    fit_logistic,
    ground_truth_comparison,
    proportion_table,
)

__all__ = ["ReportArtifacts", "build_report", "SYNTHETIC_BANNER"]

SYNTHETIC_BANNER = (
    "SYNTHETIC DEMO DATA - generated by a scripted mock agent, not real agent behaviour"
)

FACTORS = ("agent", "model", "task", "placement", "prompt")


@dataclass
class ReportArtifacts:
    """What a report build produced."""

    figures: dict[str, Path]
    tables: dict[str, Path]
    report: Path
    fit: LogitFit


def _is_synthetic(metadata: dict[str, Any]) -> bool:
    return bool(metadata.get("synthetic"))


def _banner(metadata: dict[str, Any]) -> str:
    if _is_synthetic(metadata):
        return SYNTHETIC_BANNER
    return "Real agent run - results describe the agents, models and date listed below"


def _stamp(figure: plt.Figure, metadata: dict[str, Any], title: str) -> None:
    figure.suptitle(title, fontsize=13, fontweight="bold")
    figure.text(
        0.5,
        0.005,
        _banner(metadata),
        ha="center",
        va="bottom",
        fontsize=8,
        color="#b00020" if _is_synthetic(metadata) else "#333333",
    )


def _save(figure: plt.Figure, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    figure.tight_layout(rect=(0, 0.02, 1, 0.96))
    figure.savefig(path, dpi=140)
    plt.close(figure)
    return path


def markdown_table(frame: pd.DataFrame, float_format: str = "{:.3f}") -> str:
    """Render a dataframe as a markdown table."""
    if frame.empty:
        return "_no rows_"
    header = "| " + " | ".join(str(column) for column in frame.columns) + " |"
    divider = "| " + " | ".join("---" for _ in frame.columns) + " |"
    lines = [header, divider]
    for _, row in frame.iterrows():
        cells = []
        for value in row:
            if isinstance(value, float):
                cells.append("" if np.isnan(value) else float_format.format(value))
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _rate_figure(frame: pd.DataFrame, metadata: dict[str, Any], path: Path) -> Path:
    """The exposure rate for every level of every factor."""
    figure, axes = plt.subplots(1, len(FACTORS), figsize=(16, 4.2))
    for axis, factor in zip(axes, FACTORS, strict=True):
        if factor not in frame.columns:
            axis.set_visible(False)
            continue
        table = proportion_table(frame, [factor], "exposed")
        positions = np.arange(len(table))
        lower, upper = _error_bars(table["rate"], table["ci_low"], table["ci_high"])
        axis.bar(positions, table["rate"], color="#4c72b0")
        axis.errorbar(
            positions,
            table["rate"],
            yerr=[lower, upper],
            fmt="none",
            ecolor="#222222",
            capsize=4,
        )
        axis.set_xticks(positions)
        axis.set_xticklabels(table[factor], rotation=35, ha="right", fontsize=8)
        axis.set_ylim(0, 1)
        axis.set_title(factor, fontsize=11)
        axis.set_ylabel("exposure rate")
        axis.grid(axis="y", alpha=0.25)
    _stamp(figure, metadata, "Exposure rate by factor level")
    return _save(figure, path)


def _heatmap_figure(frame: pd.DataFrame, metadata: dict[str, Any], path: Path) -> Path:
    """The exposure rate for every placement and prompt combination."""
    table = proportion_table(frame, ["placement", "prompt"], "exposed")
    pivot = table.pivot(index="placement", columns="prompt", values="rate")
    figure, axis = plt.subplots(figsize=(9, 4.2))
    image = axis.imshow(pivot.to_numpy(), cmap="Blues", vmin=0, vmax=1, aspect="auto")
    axis.set_xticks(range(len(pivot.columns)))
    axis.set_xticklabels(pivot.columns, rotation=25, ha="right")
    axis.set_yticks(range(len(pivot.index)))
    axis.set_yticklabels(pivot.index)
    axis.set_xlabel("prompt wording")
    axis.set_ylabel("credential placement")
    for row in range(pivot.shape[0]):
        for column in range(pivot.shape[1]):
            value = pivot.iat[row, column]
            if not np.isnan(value):
                axis.text(
                    column,
                    row,
                    f"{value:.2f}",
                    ha="center",
                    va="center",
                    fontsize=9,
                    color="white" if value > 0.55 else "#111111",
                )
    figure.colorbar(image, ax=axis, label="exposure rate")
    _stamp(figure, metadata, "Exposure rate by placement and prompt wording")
    return _save(figure, path)


def _odds_ratio_figure(fit: LogitFit, metadata: dict[str, Any], path: Path) -> Path:
    """A forest plot of the odds ratios."""
    terms = fit.terms[fit.terms["term"] != "const"].copy()
    figure, axis = plt.subplots(figsize=(9, max(3.0, 0.45 * len(terms))))
    if terms.empty:
        axis.text(0.5, 0.5, "no estimable terms", ha="center", va="center")
        axis.set_axis_off()
        return _save(figure, path)
    positions = np.arange(len(terms))
    axis.errorbar(
        terms["odds_ratio"],
        positions,
        xerr=[
            terms["odds_ratio"] - terms["ci_low"],
            terms["ci_high"] - terms["odds_ratio"],
        ],
        fmt="o",
        color="#4c72b0",
        ecolor="#222222",
        capsize=4,
    )
    axis.axvline(1.0, color="#b00020", linestyle="--", linewidth=1)
    axis.set_yticks(positions)
    axis.set_yticklabels(terms["term"], fontsize=8)
    axis.set_xscale("log")
    axis.set_xlabel("odds ratio (log scale)")
    axis.grid(axis="x", alpha=0.25)
    _stamp(figure, metadata, "Odds ratios from the logistic model")
    return _save(figure, path)


def _outcome_figure(frame: pd.DataFrame, metadata: dict[str, Any], path: Path) -> Path:
    """The rate of every outcome signal."""
    outcomes = ["read_any", "exfil", "use", "disclosed", "exposed"]
    rows = []
    for outcome in outcomes:
        successes = int(frame[outcome].sum())
        low, high = _interval(successes, len(frame))
        rows.append((outcome, successes / len(frame), low, high))
    figure, axis = plt.subplots(figsize=(8, 4.0))
    labels = [row[0] for row in rows]
    positions = np.arange(len(rows))
    lower, upper = _error_bars(
        [row[1] for row in rows], [row[2] for row in rows], [row[3] for row in rows]
    )
    axis.bar(positions, [row[1] for row in rows], color="#55a868")
    axis.errorbar(
        positions,
        [row[1] for row in rows],
        yerr=[lower, upper],
        fmt="none",
        ecolor="#222222",
        capsize=4,
    )
    axis.set_xticks(positions)
    axis.set_xticklabels(labels)
    axis.set_ylim(0, 1)
    axis.set_ylabel("rate")
    axis.grid(axis="y", alpha=0.25)
    _stamp(figure, metadata, "Outcome rates, with 95% Wilson intervals")
    return _save(figure, path)


def _error_bars(rates: Sequence[float], lows: Sequence[float], highs: Sequence[float]):
    """The lower and upper error bar lengths, clipped at zero.

    A rate of exactly zero or one leaves a Wilson bound a rounding error
    outside the estimate, and matplotlib rejects a negative error bar.
    """
    lower = np.maximum(0.0, np.asarray(rates, dtype=float) - np.asarray(lows, dtype=float))
    upper = np.maximum(0.0, np.asarray(highs, dtype=float) - np.asarray(rates, dtype=float))
    return lower, upper


def _relative(target: Path, report: Path) -> str:
    """A link from the report to a figure, relative to the report."""
    try:
        return os.path.relpath(target, report.parent)
    except ValueError:  # pragma: no cover - different drives on Windows
        return str(target)


def _interval(successes: int, total: int) -> tuple[float, float]:
    from abstudy.analysis import wilson_interval

    return wilson_interval(successes, total)


def _factor_rate_table(frame: pd.DataFrame) -> pd.DataFrame:
    """The exposure rate for every level of every factor, in one table."""
    rows = []
    for factor in FACTORS:
        if factor not in frame.columns:
            continue
        for _, row in proportion_table(frame, [factor], "exposed").iterrows():
            rows.append(
                {
                    "factor": factor,
                    "level": row[factor],
                    "n": row["n"],
                    "events": row["events"],
                    "rate": row["rate"],
                    "ci_low": row["ci_low"],
                    "ci_high": row["ci_high"],
                }
            )
    return pd.DataFrame(rows)


def _headline(frame: pd.DataFrame) -> dict[str, Any]:
    total = len(frame)
    values: dict[str, Any] = {"n": total}
    for outcome in ("exposed", "read_any", "exfil", "use", "disclosed"):
        successes = int(frame[outcome].sum())
        low, high = _interval(successes, total)
        values[outcome] = {
            "events": successes,
            "rate": successes / total if total else float("nan"),
            "ci_low": low,
            "ci_high": high,
        }
    return values


def _comparison_table(frame: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for factor in FACTORS:
        if factor not in frame.columns:
            continue
        levels = list(frame[factor].dropna().unique())
        if len(levels) < 2:
            continue
        try:
            result = fisher_comparison(frame, "exposed", factor, reference=levels[0])
        except ValueError:
            continue
        rows.append(
            {
                "factor": factor,
                "reference": result["reference"],
                "reference_rate": result["reference_events"] / max(result["reference_n"], 1),
                "compared": ", ".join(result["compared"]),
                "compared_rate": result["compared_events"] / max(result["compared_n"], 1),
                "odds_ratio": result["odds_ratio"],
                "p_value": result["p_value"],
            }
        )
    return pd.DataFrame(rows)


def build_report(
    frame: pd.DataFrame,
    metadata: dict[str, Any],
    out_dir: str | Path,
    report_path: str | Path | None = None,
) -> ReportArtifacts:
    """Build the figures, the tables and the report.

    ``frame`` is the tidy result table. Failed trials are excluded from the
    analysis and counted separately, because a trial that crashed says
    nothing about the agent.
    """
    out = Path(out_dir)
    figures_dir = out / "figures"
    tables_dir = out / "tables"
    figures_dir.mkdir(parents=True, exist_ok=True)
    tables_dir.mkdir(parents=True, exist_ok=True)

    usable = frame[frame["error"].isna() | (frame["error"] == "")].copy()
    excluded = len(frame) - len(usable)

    figures: dict[str, Path] = {}
    tables: dict[str, Path] = {}

    figures["rates_by_factor"] = _rate_figure(usable, metadata, figures_dir / "rates_by_factor.png")
    figures["placement_prompt"] = _heatmap_figure(
        usable, metadata, figures_dir / "placement_prompt.png"
    )
    figures["outcomes"] = _outcome_figure(usable, metadata, figures_dir / "outcomes.png")

    fit = fit_logistic(usable, "exposed", FACTORS, cluster="task")
    figures["odds_ratios"] = _odds_ratio_figure(fit, metadata, figures_dir / "odds_ratios.png")

    headline = _headline(usable)

    factor_rates = _factor_rate_table(usable)
    conditional = conditional_exposure(usable)
    detectors = detector_agreement(usable)
    comparisons = _comparison_table(usable)
    truth = ground_truth_comparison(usable, metadata.get("ground_truth") or [])

    tables["factor_rates"] = tables_dir / "factor_rates.csv"
    tables["factor_rates"].write_text(factor_rates.to_csv(index=False))
    tables["model"] = tables_dir / "model.csv"
    tables["model"].write_text(fit.terms.to_csv(index=False))
    tables["conditional_exposure"] = tables_dir / "conditional_exposure.csv"
    tables["conditional_exposure"].write_text(conditional.to_csv(index=False))
    tables["detector_agreement"] = tables_dir / "detector_agreement.csv"
    tables["detector_agreement"].write_text(detectors.to_csv(index=False))
    tables["comparisons"] = tables_dir / "comparisons.csv"
    tables["comparisons"].write_text(comparisons.to_csv(index=False))
    if not truth.empty:
        tables["ground_truth"] = tables_dir / "ground_truth.csv"
        tables["ground_truth"].write_text(truth.to_csv(index=False))

    report = Path(report_path) if report_path else out / "report.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(
        _render_report(
            usable=usable,
            metadata=metadata,
            headline=headline,
            factor_rates=factor_rates,
            fit=fit,
            conditional=conditional,
            detectors=detectors,
            comparisons=comparisons,
            truth=truth,
            excluded=excluded,
            figures=figures,
            report=report,
        )
    )

    return ReportArtifacts(
        figures=figures,
        tables=tables,
        report=report,
        fit=fit,
    )


def _render_report(
    *,
    usable: pd.DataFrame,
    metadata: dict[str, Any],
    headline: dict[str, Any],
    factor_rates: pd.DataFrame,
    fit: LogitFit,
    conditional: pd.DataFrame,
    detectors: pd.DataFrame,
    comparisons: pd.DataFrame,
    truth: pd.DataFrame,
    excluded: int,
    figures: dict[str, Path],
    report: Path,
) -> str:
    synthetic = _is_synthetic(metadata)
    lines: list[str] = []

    lines.append("# Study report")
    lines.append("")
    if synthetic:
        lines.append("> **SYNTHETIC DATASET.** Every number below was produced by a scripted")
        lines.append("> mock agent with a known behaviour model. It is a test of the")
        lines.append("> measurement pipeline, not a finding about any real agent. The mock")
        lines.append("> agent reads, leaks or ignores credentials according to the")
        lines.append("> probabilities recorded in the run metadata; the analysis below")
        lines.append("> recovers those planted effects, which is what makes the pipeline")
        lines.append("> checkable.")
        lines.append("")
    lines.append(f"**Banner:** {_banner(metadata)}")
    lines.append("")

    lines.append("## 1. Provenance")
    lines.append("")
    provenance = pd.DataFrame(
        [
            {"field": "study", "value": metadata.get("study", "unknown")},
            {"field": "dataset", "value": metadata.get("dataset", "unknown")},
            {"field": "synthetic", "value": "yes" if synthetic else "no"},
            {"field": "started", "value": metadata.get("started_at", "unknown")},
            {"field": "finished", "value": metadata.get("finished_at", "unknown")},
            {"field": "trials run", "value": metadata.get("n_trials", len(usable))},
            {"field": "trials analysed", "value": len(usable)},
            {"field": "trials excluded (errors)", "value": excluded},
            {"field": "config", "value": metadata.get("config_path", "unknown")},
        ]
    )
    lines.append(markdown_table(provenance, "{:.0f}"))
    lines.append("")

    lines.append("## 2. Headline")
    lines.append("")
    headline_rows = []
    for outcome in ("read_any", "exposed", "exfil", "use", "disclosed"):
        values = headline[outcome]
        headline_rows.append(
            {
                "outcome": outcome,
                "events": values["events"],
                "n": headline["n"],
                "rate": values["rate"],
                "ci_low": values["ci_low"],
                "ci_high": values["ci_high"],
            }
        )
    lines.append(markdown_table(pd.DataFrame(headline_rows)))
    lines.append("")
    lines.append(
        "Intervals are Wilson score intervals at 95%. The primary outcome is"
        " `exposed`: the credential was sent out (`exfil`) or used (`use`)."
    )
    lines.append("")

    lines.append("## 3. Rate by factor level")
    lines.append("")
    lines.append(markdown_table(factor_rates))
    lines.append("")
    lines.append(f"![rate by factor]({_relative(figures['rates_by_factor'], report)})")
    lines.append("")
    lines.append(f"![placement by prompt]({_relative(figures['placement_prompt'], report)})")
    lines.append("")
    lines.append(f"![outcomes]({_relative(figures['outcomes'], report)})")
    lines.append("")

    lines.append("## 4. Logistic model")
    lines.append("")
    if fit.separated:
        lines.append(f"The model could not be estimated. {fit.note}")
    else:
        lines.append(
            f"`exposed ~ C(agent) + C(model) + C(task) + C(placement) + C(prompt)`, "
            f"fitted on {fit.n} trials with cluster-robust standard errors clustered on "
            f"the task template. The reference level of each factor is the first one "
            f"alphabetically."
        )
        lines.append("")
        terms = fit.terms.copy()
        terms["significant"] = terms["p_adj"] < 0.05
        lines.append(markdown_table(terms))
        lines.append("")
        lines.append(
            f"McFadden pseudo R2 {fit.pseudo_r2:.3f}; log likelihood {fit.log_likelihood:.2f}."
        )
        if fit.note:
            lines.append("")
            lines.append(f"Note: {fit.note}.")
        lines.append("")
        lines.append(f"![odds ratios]({_relative(figures['odds_ratios'], report)})")
    lines.append("")

    lines.append("## 5. Pairwise comparisons")
    lines.append("")
    if comparisons.empty:
        lines.append("_no factor had more than one level_")
    else:
        lines.append(
            "Two-sided Fisher exact tests, one per factor, against the first level"
            " of that factor. These are the pre-registered primary contrasts; the"
            " model above adjusts for the other factors."
        )
        lines.append("")
        lines.append(markdown_table(comparisons))
    lines.append("")

    lines.append("## 6. Conditional exposure")
    lines.append("")
    lines.append(
        "Of the trials that read the credential, how many leaked or used it. This"
        " separates agents that read everything from agents that read but do not"
        " leak."
    )
    lines.append("")
    lines.append(markdown_table(conditional))
    lines.append("")

    lines.append("## 7. Detector agreement")
    lines.append("")
    lines.append(
        "The same leak is often seen by more than one detector. The rate below is"
        " what each detector found on its own."
    )
    lines.append("")
    lines.append(markdown_table(detectors))
    lines.append("")

    if not truth.empty:
        lines.append("## 8. Ground truth check")
        lines.append("")
        lines.append(
            "The mock agent's behaviour is known exactly, so the measurement can be"
            " checked against it. The designed rate is what the mock was configured"
            " to produce; the observed rate is what the harness measured. A gap"
            " between them means the measurement is wrong."
        )
        lines.append("")
        lines.append(markdown_table(truth))
        lines.append("")

    lines.append("## 9. What this does not show")
    lines.append("")
    lines.append(
        "The design, the threats to validity and the ethics are in"
        " [docs/study-design.md](../docs/study-design.md). The short version:"
    )
    lines.append("")
    lines.append(
        "* Planted credentials carry a `TRIPWIRE` marker, so a capable agent may"
        " recognise them as decoys. This inflates the rate at which agents ignore"
        " credentials."
    )
    lines.append(
        "* On macOS a file read cannot be attributed to a process, so `watch` may"
        " credit an agent with a read caused by an indexer."
    )
    lines.append(
        "* A sandbox has no cloud provider, no CI system and no teammate, so the"
        " most likely real-world exfiltration paths are partly missing."
    )
    lines.append(
        "* Model identifiers are a promise about a moving target. Any real result"
        " must state the date it was collected."
    )
    if synthetic:
        lines.append(
            "* **This dataset is synthetic. It says nothing at all about how any"
            " real agent behaves.**"
        )
    lines.append("")

    lines.append("## 10. Reproducing this run")
    lines.append("")
    lines.append("```sh")
    lines.append("uv sync --all-groups")
    lines.append(
        f"uv run abs study run --config {metadata.get('config_path', 'configs/demo.toml')} \\"
    )
    lines.append(f"    --out results/{metadata.get('dataset', 'run')}")
    lines.append(f"uv run abs study analyze --results results/{metadata.get('dataset', 'run')} \\")
    lines.append(f"    --out reports/{metadata.get('dataset', 'run')}")
    lines.append("```")
    lines.append("")
    return "\n".join(lines) + "\n"


def load_metadata(run_dir: str | Path) -> dict[str, Any]:
    """Read the run metadata written next to a result file."""
    path = Path(run_dir)
    if path.is_dir():
        path = path / "run.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text())


def write_metadata(run_dir: str | Path, metadata: dict[str, Any]) -> Path:
    """Write the run metadata next to a result file."""
    path = Path(run_dir)
    if path.is_dir():
        path = path / "run.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(metadata, indent=2, default=str) + "\n")
    return path


def figure_listing(artifacts: ReportArtifacts) -> Sequence[str]:
    """The figure paths, in a stable order."""
    return list(artifacts.figures.values())
